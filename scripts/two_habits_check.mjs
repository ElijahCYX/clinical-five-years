console.log('after one confirm disabled:', await page.locator('.plan-footer .btn-primary').isDisabled())
await page.locator('.habit-card',{hasText:'早睡'}).click()
console.log('after two confirm disabled:', await page.locator('.plan-footer .btn-primary').isDisabled())
console.log('summary:', (await page.locator('.plan-summary').innerText()).replace(/\n/g,' | '))
await page.locator('.plan-footer .btn-primary').click(); await page.waitForTimeout(400)
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('clinical-five-years-save-v12')).game)
console.log('saved habits:', saved.habits)
console.log('rail:', (await page.locator('.plan-card-mini').innerText()).replace(/\n/g,' | '))
const floors=await page.evaluate(async()=>{const g=await import('/src/game.ts'); const all=[]; for(let i=0;i<20;i++){all.push(g.cetScore('cet4',0,2),g.cetScore('cet6',0,2))} return {min4:Math.min(...all.filter((_,i)=>i%2===0)),min6:Math.min(...all.filter((_,i)=>i%2===1))}})
