import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true, args:['--no-sandbox','--disable-gpu'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } })
const errors=[]
page.on('pageerror', e => errors.push(e.message))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })
await page.locator('.title-actions .btn-primary').click(); await page.waitForTimeout(250)
await page.locator('.field input').first().fill('预览测试')
await page.locator('.confirm-box .btn-primary').click(); await page.waitForTimeout(300)
await page.locator('.plan-card', { hasText: '周期回顾' }).click()
await page.locator('.habit-card', { hasText: '时间管理' }).click()
await page.locator('.plan-footer .btn-primary').click(); await page.waitForTimeout(300)
await page.locator('.action-card', { hasText: '泡图书馆' }).click()
await page.locator('.action-card', { hasText: '纯粹的休息' }).click()
await page.waitForTimeout(200)
const before = (await page.locator('.status-card').innerText()).replace(/\n/g,' | ')
await page.locator('.action-footer .btn-primary').click(); await page.waitForTimeout(500)
const after = (await page.locator('.status-card').innerText()).replace(/\n/g,' | ')
console.log('BEFORE:', before)
console.log('AFTER:', after)
console.log('errors:', errors)
await browser.close()
