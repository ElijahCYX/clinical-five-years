import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true, args:['--no-sandbox','--disable-gpu'] })
const page = await browser.newPage({ viewport:{width:1400,height:1000} })
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'})
const r=await page.evaluate(async()=>{const m=await import('/src/names.ts'); const names=m.NAME_LIBRARY; const lens={}; for(const n of names) lens[n.length]=(lens[n.length]||0)+1; return {count:names.length,unique:new Set(names).size,lens,bad:names.filter(n=>!/^[\u4e00-\u9fa5]{2,4}$/.test(n)).slice(0,5)}})
console.log(r)
await page.locator('.title-actions .btn-primary').click(); await page.waitForTimeout(300)
console.log('random button:', await page.locator('.name-random-btn').count())
await page.locator('.name-random-btn').click(); await page.waitForTimeout(150)
const value=await page.locator('.name-input-row input').inputValue()
console.log('random name:', value, 'len', [...value].length)
console.log('errors:', errors.slice(0,5))
await browser.close()
