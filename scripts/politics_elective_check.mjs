import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true, args:['--no-sandbox','--disable-gpu'] })
const page = await browser.newPage({ viewport:{width:1500,height:1200} })
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'})
const data=await page.evaluate(async()=>{
  const g=await import('/src/game.ts'); const d=await import('/src/data.ts'); const demo=await import('/src/demo.ts')
  const seasonCredits=d.SEASONS.reduce((sum,s)=>sum+s.courses.reduce((x,c)=>x+c.credits,0),0)
  const byType={}; for(const c of d.ELECTIVE_COURSES) byType[c.electiveType]=(byType[c.electiveType]||0)+1
  return {seasonCredits, plusPE:seasonCredits+10, totalElectives:d.ELECTIVE_COURSES.length, byType, offers:g.newGameState(demo.demoPlayer).electiveOffers.length}
})
console.log(JSON.stringify(data,null,2))
await page.evaluate(()=>localStorage.clear()); await page.reload({waitUntil:'networkidle'})
await page.locator('.title-actions .btn-primary').click(); await page.waitForTimeout(250)
await page.locator('.field input').first().fill('思政测试'); await page.locator('.confirm-box .btn-primary').click(); await page.waitForTimeout(300)
await page.locator('.opening-talent-card').first().click(); await page.locator('.talent-select-footer .btn-primary').click(); await page.waitForTimeout(400)
console.log('cards:', await page.locator('.elective-card').count())
console.log('types:', await page.locator('.elective-type').allInnerTexts())
console.log('refresh buttons:', await page.locator('.elective-refresh-btn').count())
const pol=page.locator('.elective-card.type-politics')
console.log('politics card:', (await pol.innerText()).replace(/\n/g,' | ').slice(0,250))
await pol.locator('.elective-refresh-btn').click(); await page.waitForTimeout(200)
console.log('after refresh:', (await pol.innerText()).replace(/\n/g,' | ').slice(0,120))
await pol.click(); await page.waitForTimeout(100)
await page.locator('.elective-footer .btn-primary').click(); await page.waitForTimeout(300)
console.log('result:', (await page.locator('.elective-result').innerText()).replace(/\n/g,' | ').slice(0,300))
await page.locator('.elective-result .btn-primary').click(); await page.waitForTimeout(400)
console.log('plan courses:', (await page.locator('.plan-course-card').allInnerTexts()).join(' / ').slice(0,350))
