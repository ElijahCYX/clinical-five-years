import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true, args:['--no-sandbox','--disable-gpu'] })
const page = await browser.newPage({ viewport:{width:1500,height:1200} })
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
async function reset(){ await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'}); await page.evaluate(()=>localStorage.clear()); await page.reload({waitUntil:'networkidle'}) }
async function create(name, aptitude='出色'){
  await page.locator('.title-actions .btn-primary').click(); await page.waitForTimeout(250)
  await page.locator('.field input').first().fill(name)
  await page.locator('.talent-card',{hasText:aptitude}).click()
  await page.waitForTimeout(100)
  await page.locator('.confirm-box .btn-primary').click(); await page.waitForTimeout(350)
}
await reset(); await create('天赋测试','出色')
console.log('talent screen:', await page.locator('.talent-select-screen').count())
console.log('cards:', await page.locator('.opening-talent-card').count())
console.log('refresh buttons:', await page.locator('.talent-refresh-btn').count())
console.log('names:', await page.locator('.opening-talent-card h3').allInnerTexts())
const refresh=page.locator('.talent-refresh-btn').first(); await refresh.click(); await page.waitForTimeout(200)
console.log('refresh disabled:', await refresh.isDisabled().catch(()=>false))
await page.locator('.opening-talent-card').first().click(); await page.waitForTimeout(150)
await page.locator('.talent-select-footer .btn-primary').click(); await page.waitForTimeout(400)
console.log('post screen plan:', await page.locator('.plan-screen').count())
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('clinical-five-years-save-v14')).game)
console.log('opening talent saved:', saved.openingTalent, 'english:', saved.english)
await reset(); await create('平庸测试','平庸')
console.log('plain note:', await page.locator('.talent-plain-note').innerText().catch(()=> 'none'))
console.log('plain cards:', await page.locator('.opening-talent-card').count(), 'refresh:', await page.locator('.talent-refresh-btn').count())
await page.locator('.talent-select-footer .btn-primary').click(); await page.waitForTimeout(400)
const savedPlain=await page.evaluate(()=>JSON.parse(localStorage.getItem('clinical-five-years-save-v14')).game)
console.log('plain talent:', savedPlain.openingTalent, 'plan screen:', await page.locator('.plan-screen').count())
console.log('errors:', errors.slice(0,5))
await browser.close()
