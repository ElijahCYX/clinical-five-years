import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true, args:['--no-sandbox','--disable-gpu'] })
const page = await browser.newPage({ viewport:{width:1400,height:1100} })
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'})
const counts=await page.evaluate(async()=>{const m=await import('/src/names.ts'); return {surnames:m.SURNAME_LIBRARY.length,given:m.GIVEN_NAME_LIBRARY.length,uniqueGiven:new Set(m.GIVEN_NAME_LIBRARY).size,uniqueSurname:new Set(m.SURNAME_LIBRARY).size,sample:m.randomCharacterName()}})
console.log(counts)
await page.locator('.title-actions .btn-primary').click(); await page.waitForTimeout(300)
await page.locator('.name-random-btn').click(); await page.waitForTimeout(150)
const data=await page.evaluate(()=>({name:(document.querySelector('.name-input-row input')).value,gender:[...document.querySelectorAll('.segmented button')].find(b=>b.classList.contains('is-active'))?.textContent,background:[...document.querySelectorAll('.background-card')].find(b=>b.classList.contains('is-active'))?.innerText}))
console.log(data)
console.log('name len',[...data.name].length)
console.log('errors',errors.slice(0,5))
await browser.close()
