import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true, args:['--no-sandbox','--disable-gpu'] })
const page = await browser.newPage({ viewport:{width:1500,height:1200} })
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'})
const focus=await page.evaluate(async()=>{
  const g=await import('/src/game.ts'); const data=await import('/src/data.ts'); const demo=await import('/src/demo.ts')
  const s=g.newGameState(demo.demoPlayer); s.seasonIndex=0; s.season=data.SEASONS[0]; s.plan='B'; s.habits=['timeManagement','earlySleep']; s.week=1; s.weekFocus=null; s.selected=['library','rest']
  const base=g.simulateWeek({...s,weekFocus:null}); const main=g.simulateWeek({...s,weekFocus:s.season.courses[0].id}); const balanced=g.simulateWeek({...s,weekFocus:'balanced'})
  return {courses:s.season.courses.map(c=>c.id), base:base.prep, main:main.prep, balanced:balanced.prep}
})
console.log('distribution:', JSON.stringify(focus,null,1).slice(0,700))
await page.evaluate(()=>localStorage.clear()); await page.reload({waitUntil:'networkidle'})
await page.locator('.title-actions .btn-primary').click(); await page.waitForTimeout(250)
await page.locator('.field input').first().fill('焦点测试'); await page.locator('.confirm-box .btn-primary').click(); await page.waitForTimeout(300)
await page.locator('.plan-card',{hasText:'周期回顾'}).click(); await page.locator('.habit-card',{hasText:'时间管理'}).click(); await page.locator('.habit-card',{hasText:'早睡'}).click(); await page.locator('.plan-footer .btn-primary').click(); await page.waitForTimeout(400)
console.log('modal:', await page.locator('.focus-modal').count(), await page.locator('.focus-modal h2').innerText().catch(()=> 'none'))
console.log('choices:', await page.locator('.focus-choice').allInnerTexts())
await page.locator('.focus-choice').first().click(); await page.waitForTimeout(300)
console.log('modal after:', await page.locator('.focus-modal').count())
console.log('focus bar:', (await page.locator('.week-focus-bar').innerText()).replace(/\n/g,' | '))
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('clinical-five-years-save-v13')).game)
console.log('saved focus:', saved.weekFocus)
