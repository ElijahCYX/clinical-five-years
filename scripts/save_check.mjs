import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true, args:['--no-sandbox','--disable-gpu'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })
await page.locator('.title-actions .btn-primary').click()
await page.waitForTimeout(250)
await page.locator('.field input').first().fill('测试存档')
await page.locator('.confirm-box .btn-primary').click()
await page.waitForTimeout(250)
await page.locator('.plan-card', { hasText: '周期回顾' }).click()
await page.locator('.habit-card', { hasText: '时间管理' }).click()
await page.locator('.plan-footer .btn-primary').click()
await page.waitForTimeout(350)
await page.locator('.action-card', { hasText: '泡图书馆' }).click()
await page.locator('.action-card', { hasText: '纯粹的休息' }).click()
// save via topbar first text button
await page.locator('.topbar-right .text-btn').first().click()
await page.waitForTimeout(200)
await page.locator('.topbar-right .text-btn').last().click()
await page.waitForTimeout(350)
const enabled = await page.locator('.title-actions .btn-ghost').isEnabled()
console.log('continue enabled:', enabled)
await page.locator('.title-actions .btn-ghost').click()
await page.waitForTimeout(450)
console.log('week loaded:', await page.locator('.week-screen').count())
console.log('name:', await page.locator('.student-name').innerText())
console.log('errors:', errors)
await browser.close()
