import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true, args:['--no-sandbox','--disable-gpu'] })
const page = await browser.newPage({ viewport:{width:1500,height:1200} })
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error') errors.push(m.text())})
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'}); await page.evaluate(()=>localStorage.clear()); await page.reload({waitUntil:'networkidle'})
await page.locator('.title-actions .btn-primary').click(); await page.waitForTimeout(250)
await page.locator('.field input').first().fill('天才测试'); await page.locator('.talent-card').nth(3).click(); await page.waitForTimeout(100)
await page.locator('.confirm-box .btn-primary').click(); await page.waitForTimeout(350)
console.log('cards:', await page.locator('.opening-talent-card').count(), 'title:', await page.locator('.page-title').innerText())
const refresh=page.locator('.talent-refresh-btn').first()
console.log('refresh text:', await refresh.innerText())
await refresh.click(); await page.waitForTimeout(150); await refresh.click(); await page.waitForTimeout(150)
console.log('refresh after2 disabled:', await refresh.isDisabled().catch(()=>false), 'text:', await refresh.innerText().catch(()=>'none'))
await page.locator('.opening-talent-card').nth(0).click(); await page.locator('.opening-talent-card').nth(1).click(); await page.waitForTimeout(150)
console.log('confirm disabled after two:', await page.locator('.talent-select-footer .btn-primary').isDisabled())
await page.locator('.talent-select-footer .btn-primary').click(); await page.waitForTimeout(400)
const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('clinical-five-years-save-v15')).game)
console.log('saved talents:', saved.openingTalents, 'english:', saved.english)
console.log('errors:', errors.slice(0,5))
await browser.close()
